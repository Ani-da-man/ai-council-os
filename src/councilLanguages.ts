export function getCouncilLanguage(id: string): CouncilLanguage {
  return COUNCIL_LANGUAGES.find(language => language.id === id) || COUNCIL_LANGUAGES[0];
}

export function usesReplyScript(text: unknown, id: CouncilLanguageId): text is string {
  if (typeof text !== 'string' || !text.trim()) return false;
  const script = getCouncilLanguage(id).script;
  return new RegExp(`\\p{Script=${script}}`, 'u').test(text);
}

/** Detect language from text using Unicode scripts, with a browser language model when available. */
export function detectCouncilLanguage(text: string): CouncilLanguageId {
  const scripts: Array<[CouncilLanguageId, RegExp]> = [
    ['ta', /[\u0B80-\u0BFF]/g], ['kn', /[\u0C80-\u0CFF]/g], ['ml', /[\u0D00-\u0D7F]/g],
    ['te', /[\u0C00-\u0C7F]/g], ['bn', /[\u0980-\u09FF]/g], ['gu', /[\u0A80-\u0AFF]/g]
  ];
  let best: { id: CouncilLanguageId; count: number } = { id: 'en', count: 0 };
  for (const [id, expression] of scripts) {
    const count = (text.match(expression) || []).length;
    if (count > best.count) best = { id, count };
  }
  const devanagari = (text.match(/[\u0900-\u097F]/g) || []).length;
  if (devanagari > best.count) {
    const marathi = (text.match(/(?:आहे|आहेत|नाही|माझा|माझी|माझे|करतो|करते|साठी|मला|तुम्ही|आम्ही|व्यवसाय|ग्राहक)/g) || []).length;
    const hindi = (text.match(/(?:है|हैं|नहीं|मेरा|मेरी|मेरे|करता|करती|लिए|मुझे|आप|हम|व्यवसाय|ग्राहक)/g) || []).length;
    best = { id: marathi > hindi ? 'mr' : 'hi', count: devanagari };
  }
  return best.count ? best.id : 'en';
}

export async function detectCouncilLanguageAsync(text: string): Promise<CouncilLanguageId> {
  const fallback = detectCouncilLanguage(text);
  if (!text.trim()) return 'en';
  try {
    const Detector = (window as any).LanguageDetector;
    if (Detector?.create) {
      const detector = await Detector.create({ expectedInputLanguages: COUNCIL_LANGUAGES.map(language => language.locale) });
      const results = await detector.detect(text);
      await detector.destroy?.();
      const match = COUNCIL_LANGUAGES.find(language => results?.[0]?.detectedLanguage?.toLowerCase().startsWith(language.id));
      if (match && (results[0].confidence ?? 0) >= 0.55) return match.id;
    }
  } catch { /* Use deterministic Unicode/script detection where the browser API is unavailable. */ }
  return fallback;
}

